/**
 * Registry for editor-created maps. One manifest (`authored-maps.json`) drives
 * two GENERATED modules that use static imports/literals only:
 *  - `areas/authored-areas.generated.ts` (compiler: AUTHORED_AREAS)
 *  - `src/core/authored-maps.generated.ts` (runtime `?map=` allowlist)
 * Ids are validated against ID_RE and labels are derived from the id, so no
 * free text ever reaches generated source. Node-only.
 */
import { existsSync } from "node:fs";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { configExportName } from "../map-editor/world.ts";

export type AuthoredFormat = "legacy" | "terrain";
export interface AuthoredMap {
  id: string;
  format: AuthoredFormat;
}

const ID_RE = /^[a-z0-9-]{1,64}$/;

/** Ids owned by hand-written registries. Literal on purpose (no map-select import: cycle). */
const BUILTIN_IDS: readonly string[] = [
  "juliette-ga",
  "grid-test",
  "feel-test",
  "newton-poppleford",
  "skidders-and-popp",
  "my-map",
  "demo-hills",
  "playground",
  "straight-test",
  "arena-test",
];

const GENERATED_HEADER =
  "// GENERATED by tools/map-compiler/authored-registry.ts - do not edit; edit authored-maps.json via the editors.";

function checkEntry(e: unknown): AuthoredMap {
  if (typeof e !== "object" || e === null) {
    throw new Error("authored manifest: entry is not an object");
  }
  const { id, format } = e as Record<string, unknown>;
  if (typeof id !== "string" || !ID_RE.test(id)) {
    throw new Error(`authored manifest: bad id ${JSON.stringify(id)} (must match ${ID_RE})`);
  }
  if (format !== "legacy" && format !== "terrain") {
    throw new Error(`authored manifest: unknown format ${JSON.stringify(format)} for ${id}`);
  }
  return { id, format };
}

export function parseAuthoredManifest(text: string): AuthoredMap[] {
  const raw: unknown = JSON.parse(text);
  if (!Array.isArray(raw)) throw new Error("authored manifest: expected a JSON array");
  const out: AuthoredMap[] = [];
  const seen = new Set<string>();
  for (const e of raw) {
    const entry = checkEntry(e);
    if (seen.has(entry.id)) throw new Error(`authored manifest: duplicate id ${entry.id}`);
    seen.add(entry.id);
    out.push(entry);
  }
  return out;
}

export function authoredLabel(id: string): string {
  const words = id
    .split("-")
    .filter((s) => s !== "")
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1));
  return `${words.join(" ")} (authored)`;
}

export function compilerRegistrySource(entries: readonly AuthoredMap[]): string {
  const legacy = entries.filter((e) => e.format === "legacy");
  const lines = [GENERATED_HEADER, 'import type { AreaConfig } from "./juliette-ga.config.ts";'];
  for (const e of legacy) {
    lines.push(`import { ${configExportName(e.id)} } from "./${e.id}.config.ts";`);
  }
  lines.push("");
  if (legacy.length === 0) {
    lines.push("export const AUTHORED_AREAS: Record<string, AreaConfig> = {};");
  } else {
    lines.push("export const AUTHORED_AREAS: Record<string, AreaConfig> = {");
    for (const e of legacy) lines.push(`  ${JSON.stringify(e.id)}: ${configExportName(e.id)},`);
    lines.push("};");
  }
  return `${lines.join("\n")}\n`;
}

export function runtimeRegistrySource(entries: readonly AuthoredMap[]): string {
  const lines = [GENERATED_HEADER, ""];
  if (entries.length === 0) {
    lines.push("export const AUTHORED_MAP_IDS = [] as const;");
    lines.push("export const AUTHORED_MAP_LABELS: Readonly<Record<never, string>> = {};");
    lines.push(
      'export const AUTHORED_MAP_FORMATS: Readonly<Record<never, "legacy" | "terrain">> = {};',
    );
    return `${lines.join("\n")}\n`;
  }
  const ids = entries.map((e) => JSON.stringify(e.id)).join(", ");
  lines.push(`export const AUTHORED_MAP_IDS = [${ids}] as const;`);
  lines.push("");
  lines.push(
    "export const AUTHORED_MAP_LABELS: Readonly<Record<(typeof AUTHORED_MAP_IDS)[number], string>> = {",
  );
  for (const e of entries) {
    lines.push(`  ${JSON.stringify(e.id)}: ${JSON.stringify(authoredLabel(e.id))},`);
  }
  lines.push("};");
  lines.push("");
  lines.push(
    'export const AUTHORED_MAP_FORMATS: Readonly<Record<(typeof AUTHORED_MAP_IDS)[number], "legacy" | "terrain">> = {',
  );
  for (const e of entries) lines.push(`  ${JSON.stringify(e.id)}: ${JSON.stringify(e.format)},`);
  lines.push("};");
  return `${lines.join("\n")}\n`;
}

function paths(root: string) {
  return {
    manifest: join(root, "tools", "map-compiler", "authored-maps.json"),
    compiler: join(root, "tools", "map-compiler", "areas", "authored-areas.generated.ts"),
    runtime: join(root, "src", "core", "authored-maps.generated.ts"),
  };
}

async function atomicWrite(file: string, text: string): Promise<void> {
  await mkdir(dirname(file), { recursive: true });
  const tmp = `${file}.tmp`;
  await writeFile(tmp, text, "utf8");
  await rename(tmp, file);
}

async function readManifest(file: string): Promise<AuthoredMap[]> {
  if (!existsSync(file)) return [];
  return parseAuthoredManifest(await readFile(file, "utf8"));
}

export async function regenerateAuthoredRegistry(root: string): Promise<void> {
  const p = paths(root);
  const entries = await readManifest(p.manifest);
  await atomicWrite(p.compiler, compilerRegistrySource(entries));
  await atomicWrite(p.runtime, runtimeRegistrySource(entries));
}

export async function registerAuthoredMap(
  root: string,
  entry: AuthoredMap,
): Promise<{ added: boolean }> {
  const checked = checkEntry(entry);
  if (BUILTIN_IDS.includes(checked.id)) {
    throw new Error(`${checked.id} is already a built-in map`);
  }
  if (checked.format === "legacy") {
    const cfg = join(root, "tools", "map-compiler", "areas", `${checked.id}.config.ts`);
    if (!existsSync(cfg)) throw new Error(`no area config for ${checked.id} (expected ${cfg})`);
  }
  const p = paths(root);
  const entries = await readManifest(p.manifest);
  if (entries.some((e) => e.id === checked.id)) return { added: false };
  entries.push(checked);
  await atomicWrite(p.manifest, `${JSON.stringify(entries, null, 2)}\n`);
  await atomicWrite(p.compiler, compilerRegistrySource(entries));
  await atomicWrite(p.runtime, runtimeRegistrySource(entries));
  return { added: true };
}
